function serviceText(value, fallback = "The local service could not complete the request. Please try again.") {
  if (appInfo.effectiveLanguage !== "en" || typeof value !== "string" || !/\p{Script=Han}/u.test(value)) return value;
  const text = value.trim();
  if (Object.hasOwn(serviceTextEnglish, text)) return serviceTextEnglish[text];
  const status = text.match(/^Colab 本次返回 HTTP (\d{3})，请刷新该账号核对。$/);
  if (status) return "Colab returned HTTP " + status[1] + ". Refresh the account to check.";
  const maxLength = text.match(/^请输入 1 至 (\d+) 个字符。$/);
  if (maxLength) return "Enter 1 to " + maxLength[1] + " characters.";
  const targets = { "账号名称": "account name", "Google 邮箱": "Google email", "实例名称": "instance name", "媒体文件": "media file", "作品名称": "job title" };
  const field = text.match(/^请填写(.+)。$|^(.+)须填写 1 至 (\d+) 个字符。$/);
  if (field) {
    const label = targets[field[1] || field[2]];
    if (label) return field[3] ? "Enter 1 to " + field[3] + " characters for the " + label + "." : "Enter the " + label + ".";
  }
  const download = text.match(/^下载并核对视频模型 (\d+)\/3$/);
  if (download) return "Downloading and verifying video model " + download[1] + "/3";
  const unverified = " 算力费率待核对。";
  if (text.endsWith(unverified)) {
    const prefix = text.slice(0, -unverified.length);
    if (Object.hasOwn(serviceTextEnglish, prefix)) return serviceTextEnglish[prefix] + " " + serviceTextEnglish[unverified.trim()];
  }
  return fallback;
}
